"""
X1, item 19 — o banco criado pelas migrações e o schema.sql (Apostila IV).

Colunas, tipos, tamanhos, restrições, padrões e a view de saldo são conferidos tabela a tabela nos
testes de cada tarefa (`divergencias_do_schema`). Além disso, o Django cria três detalhes que o
schema.sql não tem; o grupo decidiu em 16/11/2026 aceitá-los e registrá-los (lacuna L28, ADR-014):

1. chave primária `GENERATED BY DEFAULT AS IDENTITY` no lugar de `SERIAL` — numera igual;
2. chave estrangeira `DEFERRABLE INITIALLY DEFERRED` — conferida no fim da transação;
3. 16 índices a mais: um por chave estrangeira e um `_like` por coluna de texto única.

Este teste falha se aparecer uma quarta diferença, ou se uma dessas mudar.
"""

import importlib

import pytest
from django.db import connection

TABELAS = [
    "categoria", "fornecedor", "produto", "usuario", "lote", "movimentacao", "venda", "item_venda",
    "importacao_pdv", "consumo_diario", "previsao_produto", "alerta", "fechamento_caixa", "parametro",
]  # fmt: skip
COM_ID = [t for t in TABELAS if t not in ("consumo_diario", "previsao_produto", "parametro")]

# Os índices que o schema.sql declara: chaves primárias, UNIQUE e os quatro CREATE INDEX.
DO_SCHEMA = {f"{t}_pkey" for t in TABELAS} | {
    "categoria_nome_key",
    "usuario_login_key",
    "uq_produto_nome_categoria",
    "ix_lote_fifo",
    "ix_mov_produto_data",
    "ix_mov_tipo_data",
    "ix_alerta_pendente",
}


def _linhas(sql, parametros=()):
    with connection.cursor() as cursor:
        cursor.execute(sql, parametros)
        return cursor.fetchall()


@pytest.mark.django_db
def test_x1_chave_primaria_e_identity_no_lugar_de_serial():
    identidade = dict(
        _linhas(
            "SELECT table_name, is_identity FROM information_schema.columns "
            "WHERE column_name = 'id' AND table_name = ANY(%s)",
            [COM_ID],
        )
    )
    assert identidade == dict.fromkeys(COM_ID, "YES")


@pytest.mark.django_db
def test_x1_chaves_estrangeiras_sao_conferidas_no_fim_da_transacao():
    chaves = _linhas(
        "SELECT conname, condeferrable, condeferred FROM pg_constraint "
        "WHERE contype = 'f' AND conrelid::regclass::text = ANY(%s)",
        [TABELAS],
    )
    assert len(chaves) == 15
    assert all(adiavel and adiada for _, adiavel, adiada in chaves)


@pytest.mark.django_db
def test_x1_indices_a_mais_sao_so_os_automaticos_do_django():
    chaves_estrangeiras = {
        (tabela, coluna)
        for tabela, coluna in _linhas(
            "SELECT tc.table_name, kcu.column_name FROM information_schema.table_constraints tc "
            "JOIN information_schema.key_column_usage kcu ON kcu.constraint_name = tc.constraint_name "
            "WHERE tc.constraint_type = 'FOREIGN KEY' AND tc.table_name = ANY(%s)",
            [TABELAS],
        )
    }
    a_mais = [
        (tabela, nome, definicao)
        for tabela, nome, definicao in _linhas(
            "SELECT tablename, indexname, indexdef FROM pg_indexes WHERE tablename = ANY(%s)", [TABELAS]
        )
        if nome not in DO_SCHEMA
    ]

    assert len(a_mais) == 16
    for tabela, nome, definicao in a_mais:
        colunas = definicao.split("(", 1)[1].rsplit(")", 1)[0]
        if nome.endswith("_like"):
            assert "varchar_pattern_ops" in colunas, nome
        else:
            assert (tabela, colunas) in chaves_estrangeiras, nome


@pytest.mark.django_db
def test_x1_migracao_acerta_o_padrao_de_data_hora_do_banco_antigo():
    """
    A migração 0001 do estoque foi editada depois de aplicada: o banco criado antes dela ficou com
    statement_timestamp() em movimentacao.data_hora, e o schema.sql diz NOW(). A 0003 acerta.
    """
    migracao = importlib.import_module("estoque.migrations.0003_padrao_data_hora_now")
    with connection.cursor() as cursor:
        cursor.execute("ALTER TABLE movimentacao ALTER COLUMN data_hora SET DEFAULT statement_timestamp()")
        cursor.execute(migracao.ACERTA_O_PADRAO)
    [(padrao,)] = _linhas(
        "SELECT column_default FROM information_schema.columns "
        "WHERE table_name = 'movimentacao' AND column_name = 'data_hora'"
    )
    assert padrao == "now()"
